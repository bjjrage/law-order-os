import { z } from 'zod';
import { sha256 } from '../../../os-core/src/bytes.js';
import { extractCitationsCore } from '../../../junta-juridica/src/citation-checker/extraction-core.js';

const id = z.string().min(1).max(128);
const digest = z.string().regex(/^[a-f0-9]{64}$/);
const time = z.iso.datetime();
const scope = { law_firm_id: id, matter_id: id };
export const AssignmentSchema = z.object({
  ...scope, id, command_id: id, version: z.number().int().positive(), human_owner_id: id,
  profile_id: z.literal('elena'), pack_id: z.literal('civil_contractual'), pack_version: z.literal(1),
  assigned_by: id, created_at: time,
}).strict();
export const EvidenceSchema = z.object({
  document_id: id, version_id: id, sha256: digest, title: z.string().min(1).max(240),
  nature: z.enum(['DOCUMENT_TEXT', 'PARTY_ALLEGATION']), text: z.string().min(1).max(24576),
}).strict();
export const PlanSchema = z.object({
  ...scope, id, command_id: id, assignment_id: id, assignment_version: z.number().int().positive(),
  human_owner_id: id, question: z.string().min(15).max(2000),
  evidence: z.array(EvidenceSchema).min(1).max(4), inventory_hash: digest,
  plan_hash: digest, created_at: time, expires_at: time,
  mode: z.literal('OFFLINE_SIMULATION'), max_cost_usd: z.literal(0),
}).strict();
export const OutputSchema = z.object({
  id, author: z.enum(['HUMAN', 'DOCUMENT_ROUTER', 'CONTEXT_BUILDER', 'ELENA']),
  text: z.string().max(180000),
}).strict();
export const FindingSchema = z.object({
  kind: z.enum(['OBLIGATION', 'CONDITION', 'EXCEPTION', 'AMOUNT', 'MISSING_ANNEX', 'REPRESENTATION', 'VERSION_REVIEW']),
  document_id: id, version_id: id, start: z.number().int().nonnegative(), end: z.number().int().nonnegative(),
  quote: z.string().min(1), observation: z.string().min(1),
}).strict();
export const AuditSchema = z.object({
  checker_version: z.literal('contractual-offline-terminal-v1'), extractor_version: z.string(),
  final_content_hash: digest, manifest_hash: digest,
  outputs: z.array(z.object({ id, author: OutputSchema.shape.author, sha256: digest }).strict()).length(5),
  references: z.array(z.object({ output_id: id, author: OutputSchema.shape.author, start: z.number(), end: z.number(), text: z.string(), status: z.literal('REVIEW_REQUIRED'), reason: z.literal('NO_TRUSTED_OFFICIAL_SCOPE') }).strict()),
  status: z.enum(['NO_REFERENCES', 'REVIEW_REQUIRED']),
  coverage: z.literal('ALL_OUTPUTS_COLLECTED_GRAMMAR_LIMITED'), checked_at: time,
}).strict();
export const RunSchema = z.object({
  ...scope, id, plan_id: id, plan_hash: digest, assignment_id: id, inventory_hash: digest,
  human_owner_id: id, question: z.string(), evidence: z.array(EvidenceSchema),
  findings: z.array(FindingSchema), outputs: z.array(OutputSchema).length(5), final_markdown: z.string().max(180000),
  audit: AuditSchema, created_at: time, mode: z.literal('OFFLINE_SIMULATION'),
  human_review: z.literal('PENDING'), paid_calls: z.literal(0), actual_cost_usd: z.literal(0),
  completion_status: z.enum(['COMPLETE_DRAFT', 'NEEDS_MORE_EVIDENCE']),
  stages: z.array(z.object({ role: z.enum(['DOCUMENT_ROUTER', 'CONTEXT_BUILDER', 'ELENA', 'FINAL_CHECKER']), execution: z.literal('DETERMINISTIC_OFFLINE'), status: z.literal('COMPLETE') }).strict()).length(4),
}).strict();
export const PilotStateSchema = z.object({
  schema_version: z.literal(1),
  assignments: z.array(AssignmentSchema), plans: z.array(PlanSchema), runs: z.array(RunSchema),
  draft_links: z.array(z.object({ ...scope, run_id: id, draft_id: id, document_version_id: id, content_hash: digest, audit: AuditSchema }).strict()),
  fixture_commands: z.array(z.object({ ...scope, command_id: id, document_ids: z.array(id).length(2) }).strict()),
}).strict();
export type PilotState = z.infer<typeof PilotStateSchema>;
export type PilotPlan = z.infer<typeof PlanSchema>;
export type PilotRun = z.infer<typeof RunSchema>;
export type PilotEvidence = z.infer<typeof EvidenceSchema>;
export type PilotFinding = z.infer<typeof FindingSchema>;
export type PilotOutput = z.infer<typeof OutputSchema>;
export const emptyPilotState = (): PilotState => ({ schema_version: 1, assignments: [], plans: [], runs: [], draft_links: [], fixture_commands: [] });
export const hashText = (text: string) => sha256(new TextEncoder().encode(text));
export const hashValue = (value: unknown) => hashText(JSON.stringify(value));
export const planContent = ({ plan_hash: _hash, ...content }: PilotPlan) => content;
export async function verifyPilotPlan(plan: PilotPlan) {
  if (await hashValue(planContent(plan)) !== plan.plan_hash) throw Error('PLAN_HASH_MISMATCH');
  for (const evidence of plan.evidence) if (await hashText(evidence.text) !== evidence.sha256) throw Error('PILOT_EVIDENCE_HASH_MISMATCH');
}

// This is an offline documentary exercise, never an opinion generated by a remote model.
// All selected lines are routed and retained, including exceptions and contradictions.
export function routeContractEvidence(evidence: PilotEvidence[]) {
  return evidence.flatMap(document => {
    let start = 0;
    return document.text.split('\n').flatMap(line => {
      const at = start; start += line.length + 1;
      return line.trim() ? [{ document_id: document.document_id, version_id: document.version_id, start: at, end: at + line.length, quote: line, nature: document.nature }] : [];
    });
  });
}
export function contractualFindings(evidence: PilotEvidence[]): PilotFinding[] {
  const findings: PilotFinding[] = [];
  const lines = routeContractEvidence(evidence);
  const add = (line: typeof lines[number], kind: PilotFinding['kind'], observation: string) => findings.push({ kind, document_id: line.document_id, version_id: line.version_id, start: line.start, end: line.end, quote: line.quote, observation });
  const rules: Array<[PilotFinding['kind'], RegExp, string]> = [
    ['OBLIGATION', /(?<![\p{L}\p{N}])(?:deber[aá]|debe|obliga|pagar[aá]|entregar[aá]|prestar[aá])(?![\p{L}\p{N}])/iu, 'Prestación o deber mencionado; revisar sujeto, alcance y respaldo de cumplimiento.'],
    ['CONDITION', /\b(si|siempre que|condicionad[oa]|previa|contra recepci[oó]n|sujeto a)\b/iu, 'Condición documental a conservar; no asumir que se cumplió.'],
    ['EXCEPTION', /\b(salvo|excepto|excepci[oó]n|sin embargo|a menos que)\b/iu, 'Excepción o reserva a relacionar con la prestación afectada.'],
    ['REPRESENTATION', /\b(poder|apoderad[oa]|representante|representaci[oó]n)\b/iu, 'Verificar instrumento y facultades; la mención no acredita representación.'],
    ['VERSION_REVIEW', /\b(borrador|firmad[oa]|modificaci[oó]n|versi[oó]n)\b/iu, 'Comparar instrumentos y aceptación; el orden de carga no determina cuál rige.'],
  ];
  for (const line of lines) {
    for (const [kind, pattern, observation] of rules) if (pattern.test(line.quote)) add(line, kind, observation);
    if (/\b(?:PYG|USD)\s*[\d.,]+/iu.test(line.quote)) add(line, 'AMOUNT', 'Importe documentado; conservar moneda y condición, sin calcular deuda exigible.');
    for (const match of line.quote.matchAll(/\banexo\s+([A-Z]|\d+)\b/giu)) {
      const label = match[1]!;
      const attached = evidence.some(document => new RegExp('^anexo\\s+' + label + '(?:\\b|$)', 'iu').test(document.title) || new RegExp('^\\s*anexo\\s+' + label + '\\b', 'imu').test(document.text));
      if (!attached) add(line, 'MISSING_ANNEX', 'Remisión a Anexo ' + label + ' sin documento identificado en la selección; solicitarlo y limitar ese punto.');
    }
  }
  const amounts = new Set(lines.flatMap(line => [...line.quote.matchAll(/\b(PYG|USD)\s*([\d.,]+)/giu)].map(match => match[1]!.toUpperCase() + ' ' + match[2])));
  if (amounts.size > 1) for (const finding of findings.filter(item => item.kind === 'AMOUNT')) finding.observation += ' Hay importes diferentes en la selección; revisar si corresponden a la misma prestación, sin elegir uno silenciosamente.';
  return findings;
}

export async function auditPilotOutputs(outputs: PilotOutput[], finalMarkdown: string, checkedAt = new Date().toISOString()) {
  const expected = ['question', 'routing', 'context', 'opinion', 'final'];
  if (outputs.length !== 5 || expected.some(name => outputs.filter(output => output.id === name).length !== 1) || outputs.find(output => output.id === 'final')?.text !== finalMarkdown) throw Error('INCOMPLETE_OUTPUT_MANIFEST');
  const manifest = await Promise.all(outputs.map(async output => ({ id: output.id, author: output.author, sha256: await hashText(output.text) })));
  const references: z.infer<typeof AuditSchema>['references'] = [];
  for (const output of outputs) {
    const extracted = extractCitationsCore(output.text, 'PY', (_raw, start) => output.id + ':' + start);
    for (const item of extracted.citations) references.push({ output_id: output.id, author: output.author, start: item.start, end: item.end, text: item.citation.raw_text ?? '', status: 'REVIEW_REQUIRED', reason: 'NO_TRUSTED_OFFICIAL_SCOPE' });
    for (const item of extracted.unresolved_markers) references.push({ output_id: output.id, author: output.author, ...item, status: 'REVIEW_REQUIRED', reason: 'NO_TRUSTED_OFFICIAL_SCOPE' });
  }
  return AuditSchema.parse({ checker_version: 'contractual-offline-terminal-v1', extractor_version: 'es-bibliography-v3', final_content_hash: await hashText(finalMarkdown), manifest_hash: await hashValue(manifest), outputs: manifest, references, status: references.length ? 'REVIEW_REQUIRED' : 'NO_REFERENCES', coverage: 'ALL_OUTPUTS_COLLECTED_GRAMMAR_LIMITED', checked_at: checkedAt });
}

export async function executeContractualPilot(plan: PilotPlan): Promise<PilotRun> {
  await verifyPilotPlan(plan);
  const findings = contractualFindings(plan.evidence);
  const routing = 'Selección documental offline: se conservan todas las líneas no vacías de ' + plan.evidence.length + ' documentos; no se elimina evidencia.';
  const context = plan.evidence.map(document => document.title + ' · ' + (document.nature === 'PARTY_ALLEGATION' ? 'Alegación/borrador; no es prueba de hechos.' : 'Texto aportado; no acredita cumplimiento.') + '\n' + document.text).join('\n\n');
  const uncertainText = plan.evidence.some(document => /\uFFFD|\[\s*(?:ILEGIBLE|TRUNCADO|OCR INCIERTO)\s*\]/iu.test(document.text));
  const needsEvidence = !findings.length || uncertainText || findings.some(finding => finding.kind === 'MISSING_ANNEX');
  const opinion = (uncertainText ? 'Texto ilegible o extracción incompleta: solicitar original legible; no completar contenido por plausibilidad.\n\n' : '') + (findings.length ? findings.map((finding, index) => `${index + 1}. ${finding.observation}\nDocumento: ${plan.evidence.find(document => document.document_id === finding.document_id)!.title} · posición ${finding.start}–${finding.end}\nTexto: ${finding.quote}`).join('\n\n') : 'No se identificaron patrones contractuales dentro de las reglas limitadas del piloto. Esto no demuestra ausencia de problemas; ampliar documentación o revisión humana.');
  const finalMarkdown = '# Elena · revisión contractual documental\n\nSIMULACIÓN OFFLINE · DATOS SINTÉTICOS · BORRADOR PARA REVISIÓN HUMANA\n\n## Pregunta\n\n' + plan.question + '\n\n## Observaciones documentales\n\n' + opinion + '\n\n## Alternativas y faltantes\n\nConfirmar versión aceptada, anexos completos, representación y evidencia de cumplimiento. Si hay discrepancias, pedir aclaración y conservar ambas versiones. No se determina validez, incumplimiento ni deuda.\n\n## Alcance\n\nProcedimiento determinístico limitado; no es un análisis generativo ni una evaluación de pericia jurídica. No se consultaron fuentes jurídicas externas ni se autenticaron referencias. Todo respaldo jurídico queda pendiente. Originales localizables en el asunto.\n\n## Evidencia seleccionada\n\n' + context;
  const outputs: PilotOutput[] = [{ id: 'question', author: 'HUMAN', text: plan.question }, { id: 'routing', author: 'DOCUMENT_ROUTER', text: routing }, { id: 'context', author: 'CONTEXT_BUILDER', text: context }, { id: 'opinion', author: 'ELENA', text: opinion }, { id: 'final', author: 'ELENA', text: finalMarkdown }];
  const createdAt = new Date().toISOString();
  const audit = await auditPilotOutputs(outputs, finalMarkdown, createdAt);
  return RunSchema.parse({ law_firm_id: plan.law_firm_id, matter_id: plan.matter_id, id: 'elena:' + plan.plan_hash.slice(0, 40), plan_id: plan.id, plan_hash: plan.plan_hash, assignment_id: plan.assignment_id, inventory_hash: plan.inventory_hash, human_owner_id: plan.human_owner_id, question: plan.question, evidence: plan.evidence, findings, outputs, final_markdown: finalMarkdown, audit, created_at: createdAt, mode: 'OFFLINE_SIMULATION', human_review: 'PENDING', completion_status: needsEvidence ? 'NEEDS_MORE_EVIDENCE' : 'COMPLETE_DRAFT', paid_calls: 0, actual_cost_usd: 0, stages: ['DOCUMENT_ROUTER', 'CONTEXT_BUILDER', 'ELENA', 'FINAL_CHECKER'].map(role => ({ role, execution: 'DETERMINISTIC_OFFLINE', status: 'COMPLETE' })) });
}

export async function verifyPilotRun(run: PilotRun) {
  RunSchema.parse(run);
  const audit = await auditPilotOutputs(run.outputs, run.final_markdown, run.audit.checked_at);
  if (JSON.stringify(audit) !== JSON.stringify(run.audit)) throw Error('PILOT_AUDIT_HASH_MISMATCH');
  for (const document of run.evidence) if (await hashText(document.text) !== document.sha256) throw Error('PILOT_EVIDENCE_HASH_MISMATCH');
  for (const finding of run.findings) {
    const document = run.evidence.find(item => item.document_id === finding.document_id && item.version_id === finding.version_id);
    if (!document || document.text.slice(finding.start, finding.end) !== finding.quote) throw Error('PILOT_FINDING_PROVENANCE_MISMATCH');
  }
}

