function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, canonical(value[key])]),
    );
  return value;
}
export const fingerprint = (value) =>
  createHash("sha256")
    .update(
      typeof value === "string" ? value : JSON.stringify(canonical(value)),
    )
    .digest("hex");
export function mergeWorkspaceSources(...groups) {
  const sources = new Map();
  for (const source of groups.flat()) {
    const previous = sources.get(source.source_id);
    if (!previous) {
      sources.set(source.source_id, structuredClone(source));
      continue;
    }
    if (
      previous.version_id &&
      source.version_id &&
      previous.version_id !== source.version_id
    )
      throw Error("WORKSPACE_SOURCE_VERSION_CONFLICT");
    for (const passage of source.excerpts) {
      const prior = previous.excerpts.find(
        (p) => p.passage_id === passage.passage_id,
      );
      if (prior && prior.text !== passage.text)
        throw Error("WORKSPACE_SOURCE_VERSION_CONFLICT");
      if (!prior) previous.excerpts.push(structuredClone(passage));
    }
  }
  return [...sources.values()];
}

