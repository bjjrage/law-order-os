/** Exact document passage ids are generated by the host. Literal presence is
 * evidence of wording, never authentication of a legal source. */
export function referenceQuoteMatches(reference, sources, evidence = {}) {
  if (!reference.quote.trim()) return false;
  const source = sources.find((s) => s.source_id === reference.source_id);
  let text = source?.excerpts.find(
    (p) => p.passage_id === reference.passage_id,
  )?.text;
  if (text === undefined) {
    const context = evidence.context ?? evidence;
    const document = [
      { document_id: "EDITOR", text: context.text ?? context.quote ?? "" },
      ...(context.attached_documents ?? []),
    ].find((d) => d.document_id === reference.source_id);
    const prefix = `${reference.source_id}:P`;
    const index = reference.passage_id.startsWith(prefix)
      ? reference.passage_id.slice(prefix.length)
      : "";
    if (document && /^[1-9]\d*$/.test(index))
      text = document.text.split("\n")[Number(index) - 1];
  }
  return (
    text !== undefined &&
    text
      .replace(/\s+/g, " ")
      .includes(reference.quote.replace(/\s+/g, " ").trim())
  );
}

/** Read-only tools over the frozen authorized snapshot. These extract text,
 * never determine legal effect, calculate liability or silently select a version. */
export function specialistEvidence(profile, context) {
  const documents = [
    {
      document_id: "EDITOR",
      version_id: "FROZEN_EDITOR",
      title: context.title,
      text: context.quote ?? context.text ?? "",
    },
    ...(context.attached_documents ?? []),
  ];
  const inventory = documents.map((d) => ({
    document_id: d.document_id,
    version_id: d.version_id,
    title: d.title,
    text_sha256: fingerprint(d.text),
    chars: d.text.length,
    warnings: d.warnings ?? [],
  }));
  const passages = documents.flatMap((d) => {
    let offset = 0;
    return d.text.split("\n").map((text, i) => {
      const row = {
        document_id: d.document_id,
        version_id: d.version_id,
        passage_id: `${d.document_id}:P${i + 1}`,
        from: offset,
        to: offset + text.length,
      };
      offset += text.length + 1;
      return row;
    });
  });
  const mentions = documents.flatMap((d) =>
    [
      ...d.text.matchAll(
        /\b(?:\d{4}-\d{2}(?:-\d{2})?|\d{1,2}\/\d{1,2}\/\d{4}|(?:USD|PYG|Gs\.)\s*[\d.,]+)/giu,
      ),
    ].map((m) => ({
      document_id: d.document_id,
      version_id: d.version_id,
      from: m.index,
      to: m.index + m[0].length,
      quote: m[0],
    })),
  );
  return {
    executed_tools: [
      "document_inventory_v1",
      "exact_passage_index_v1",
      "date_amount_mentions_v1",
    ],
    inventory,
    passages,
    mentions,
    limits: [
      "Fechas e importes son menciones textuales; no acreditan hechos, plazos ni deuda.",
      "Los pasajes remiten al texto íntegro recibido. Los anexos no reemplazan automáticamente el documento abierto.",
    ],
    requested_matrix_columns: profile.output_columns,
  };
}

export function compareEvidenceVersions(context, leftId, rightId) {
  const docs = [
    {
      document_id: "EDITOR",
      text: context.document?.text ?? context.quote ?? context.text,
    },
    ...(context.attached_documents ?? []),
  ];
  const left = docs.find((d) => d.document_id === leftId),
    right = docs.find((d) => d.document_id === rightId);
  if (!left || !right || left === right)
    throw Error("WORKSPACE_EVIDENCE_NOT_FOUND");
  let from = 0,
    suffix = 0;
  while (
    from < Math.min(left.text.length, right.text.length) &&
    left.text[from] === right.text[from]
  )
    from++;
  while (
    suffix < Math.min(left.text.length, right.text.length) - from &&
    left.text.at(-suffix - 1) === right.text.at(-suffix - 1)
  )
    suffix++;
  // Keep UTF-16 offsets without cutting an emoji in half at the diff boundary.
  const cutsPair = (text, at) =>
    at > 0 &&
    at < text.length &&
    /[\uD800-\uDBFF]/.test(text[at - 1]) &&
    /[\uDC00-\uDFFF]/.test(text[at]);
  if (cutsPair(left.text, from) || cutsPair(right.text, from)) from--;
  if (
    cutsPair(left.text, left.text.length - suffix) ||
    cutsPair(right.text, right.text.length - suffix)
  )
    suffix--;
  return {
    tool_id: "exact_version_comparison_v1",
    left_id: leftId,
    right_id: rightId,
    left_sha256: fingerprint(left.text),
    right_sha256: fingerprint(right.text),
    identical: left.text === right.text,
    common_prefix_chars: from,
    common_suffix_chars: suffix,
    removed: left.text.slice(from, left.text.length - suffix),
    added: right.text.slice(from, right.text.length - suffix),
    limitation:
      "Comparación textual exacta del tramo diferente. No decide qué versión rige ni interpreta efectos jurídicos.",
  };
}

